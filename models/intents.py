"""Canonical patient intents. DistilBERT classifies into these labels."""

from enum import Enum


class Intent(str, Enum):
    CREATE_REMINDER = "CREATE_REMINDER"
    DELETE_REMINDER = "DELETE_REMINDER"
    CHECK_REMINDER = "CHECK_REMINDER"
    CHECK_MEDICATION = "CHECK_MEDICATION"
    CHECK_APPOINTMENT = "CHECK_APPOINTMENT"
    CREATE_APPOINTMENT = "CREATE_APPOINTMENT"
    ASK_PERSON_IDENTITY = "ASK_PERSON_IDENTITY"
    ASK_MEMORY = "ASK_MEMORY"
    STORE_MEMORY = "STORE_MEMORY"
    ASK_DAILY_ROUTINE = "ASK_DAILY_ROUTINE"
    CHECK_TIME = "CHECK_TIME"
    CHECK_DATE = "CHECK_DATE"
    MAKE_CALL = "MAKE_CALL"
    EMERGENCY = "EMERGENCY"
    GENERAL_CONVERSATION = "GENERAL_CONVERSATION"
    UNKNOWN = "UNKNOWN"


INTENT_LABELS: list[str] = [intent.value for intent in Intent]
